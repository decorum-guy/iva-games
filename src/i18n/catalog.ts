export type Message = keyof typeof messages;
export type Parameters = Readonly<Record<string, string | number>>;
export type Translate = (key: Message, params?: Parameters) => string;

export function translator(locale: Locale): Translate {
  return (key, params = {}) => {
    const variants: Pair | undefined = messages[key];
    if (!variants) {
      if (import.meta.env.DEV) throw new Error(`Unknown message: ${key}`);
      return messages['error.invalidCommand'][locale === 'ru' ? 0 : 1];
    }
    const index = locale === 'ru' ? 0 : 1;
    const template = variants[index];
    const missing = [...template.matchAll(/\{(\w+)\}/g)].find(([, name]) => !Object.hasOwn(params, name));
    if (missing) {
      if (import.meta.env.DEV) throw new Error(`Missing parameter ${missing[1]} for ${key}`);
      return messages['error.invalidCommand'][index];
    }
    return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(params[name]));
  };
}

export const semanticLocale = (locale: Locale) => locale === 'ru' ? 'ru-RU' : 'en-US';

export function numberText(locale: Locale, value: number) {
  return new Intl.NumberFormat(semanticLocale(locale), { maximumFractionDigits: 0 }).format(value);
}

export function dateText(locale: Locale, value: number) {
  return new Intl.DateTimeFormat(semanticLocale(locale), { dateStyle: 'medium', timeStyle: 'short' }).format(value);
}

const counts = {
  turn: { ru: { one: 'ход игрока', few: 'хода игроков', many: 'ходов игроков', other: 'хода игрока' },
    en: { one: 'player turn', other: 'player turns' } },
  cycle: { ru: { one: 'полный цикл', few: 'полных цикла', many: 'полных циклов', other: 'полного цикла' },
    en: { one: 'full cycle', other: 'full cycles' } },
  capture: { ru: { one: 'взятие', few: 'взятия', many: 'взятий', other: 'взятия' },
    en: { one: 'capture', other: 'captures' } },
} as const;

export function countText(locale: Locale, type: keyof typeof counts, value: number) {
  const category = new Intl.PluralRules(semanticLocale(locale)).select(value);
  const forms: Partial<Record<Intl.LDMLPluralRule, string>> = counts[type][locale];
  return `${new Intl.NumberFormat(semanticLocale(locale)).format(value)} ${forms[category] ?? forms.other}`;
}
